# fw-pack.ps1 - PowerShell port of config/fw-pack.py (no Python needed)
# Usage: powershell -File fw-pack.ps1 <in.bin> <edition> <version> <out.packed.bin>
param($InBin, $Edition, $Version, $OutBin)

$OBF = [byte[]](0x47,0x22,0xC0,0x52,0x5D,0x57,0x48,0x94,0xB1,0x60,0x60,0xDB,0x6F,0xE3,0x4C,0x7C,
0xD8,0x4A,0xD6,0x8B,0x30,0xEC,0x25,0xE0,0x4C,0xD9,0x00,0x7F,0xBF,0xE3,0x54,0x05,
0xE9,0x3A,0x97,0x6B,0xB0,0x6E,0x0C,0xFB,0xB1,0x1A,0xE2,0xC9,0xC1,0x56,0x47,0xE9,
0xBA,0xF1,0x42,0xB6,0x67,0x5F,0x0F,0x96,0xF7,0xC9,0x3C,0x84,0x1B,0x26,0xE1,0x4E,
0x3B,0x6F,0x66,0xE6,0xA0,0x6A,0xB0,0xBF,0xC6,0xA5,0x70,0x3A,0xBA,0x18,0x9E,0x27,
0x1A,0x53,0x5B,0x71,0xB1,0x94,0x1E,0x18,0xF2,0xD6,0x81,0x02,0x22,0xFD,0x5A,0x28,
0x91,0xDB,0xBA,0x5D,0x64,0xC6,0xFE,0x86,0x83,0x9C,0x50,0x1C,0x73,0x03,0x11,0xD6,
0xAF,0x30,0xF4,0x2C,0x77,0xB2,0x7D,0xBB,0x3F,0x29,0x28,0x57,0x22,0xD6,0x92,0x8B)

$plain = [System.IO.File]::ReadAllBytes($InBin)

# version = b'*' + edition + b' ' + version, truncated to 16, zero-padded
$v = [System.Text.Encoding]::ASCII.GetBytes("*$Edition $Version")
if ($v.Length -gt 16) { $v = $v[0..15] }
elseif ($v.Length -lt 16) { $v = $v + [byte[]]::new(16 - $v.Length) }

# payload = plain[:0x2000] + version + plain[0x2000:]  (version SHIFTS, not overwrites)
$payload = [byte[]]::new($plain.Length + 16)
[Array]::Copy($plain, 0, $payload, 0, [Math]::Min(0x2000, $plain.Length))
if ($plain.Length -gt 0x2000) {
    [Array]::Copy($plain, 0x2000, $payload, 0x2010, $plain.Length - 0x2000)
}
[Array]::Copy($v, 0, $payload, 0x2000, 16)

# XOR obfuscation with cycling key
$packed = [byte[]]::new($payload.Length)
for ($i = 0; $i -lt $payload.Length; $i++) { $packed[$i] = $payload[$i] -bxor $OBF[$i % 128] }

# CRC-16/XMODEM (poly 0x1021, init 0x0000, no reflect, xorout 0)
$crc = 0
foreach ($b in $packed) {
    $crc = $crc -bxor ([int]$b -shl 8)
    for ($j = 0; $j -lt 8; $j++) {
        if ($crc -band 0x8000) { $crc = (($crc -shl 1) -bxor 0x1021) -band 0xFFFF }
        else { $crc = ($crc -shl 1) -band 0xFFFF }
    }
}

# digest bytes swapped, appended
$out = [byte[]]::new($packed.Length + 2)
[Array]::Copy($packed, $out, $packed.Length)
# digest stored LITTLE-endian (fw-pack.py: digest = bytes([crc_lo, crc_hi]))
$out[$packed.Length]     = $crc -band 0xFF
$out[$packed.Length + 1] = ($crc -shr 8) -band 0xFF

[System.IO.File]::WriteAllBytes($OutBin, $out)
Write-Output "packed: $OutBin ($($out.Length) bytes, crc16=0x$($crc.ToString('X4')))"